export function getToolBySlug(slug) {
  return TOOLS.find((tool) => tool.slug === slug);
}

export function getToolByPath(pathname) {
  const slug = String(pathname || "").replace(/^\/+/, "").replace(/\/+$/, "");
  return getToolBySlug(slug);
}

export function toolsByGroup() {
  return GROUP_ORDER.map((key) => ({
    key,
    ...TOOL_GROUPS[key],
    tools: TOOLS.filter((tool) => tool.group === key),
  }));
}

export function liveTools() {
  return TOOLS.filter((tool) => tool.available);
}
